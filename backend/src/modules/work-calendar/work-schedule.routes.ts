import { Router } from "express";
import { authenticate } from "../../middlewares/auth.middleware";
import { requireRole } from "../../middlewares/role.middleware";
import { workScheduleController as controller } from "./work-schedule.controller";
import { calendarExceptionController as exceptions } from "./calendar-exception.controller";

export const workScheduleRoutes = Router();
workScheduleRoutes.use(authenticate, requireRole("ADMIN"));
workScheduleRoutes.get("/holiday-presets", exceptions.presets);
workScheduleRoutes.post("/versions/:versionId/exceptions/batch-preview", exceptions.batchPreview);
workScheduleRoutes.post("/versions/:versionId/exceptions/batch", exceptions.batchCreate);
workScheduleRoutes.get("/preview", exceptions.preview);
workScheduleRoutes.get("/versions/:versionId/exceptions", exceptions.list);
workScheduleRoutes.get("/versions/:versionId/exceptions/:exceptionId", exceptions.getById);
workScheduleRoutes.post("/versions/:versionId/exceptions", exceptions.create);
workScheduleRoutes.patch("/versions/:versionId/exceptions/:exceptionId", exceptions.replace);
workScheduleRoutes.delete("/versions/:versionId/exceptions/:exceptionId", exceptions.remove);
workScheduleRoutes.get("/versions", controller.list);
workScheduleRoutes.get("/versions/:id", controller.getById);
workScheduleRoutes.post("/versions", controller.create);
workScheduleRoutes.patch("/versions/:id", controller.update);
workScheduleRoutes.post("/versions/:id/activate", controller.activate);
